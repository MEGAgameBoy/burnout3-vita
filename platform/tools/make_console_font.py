"""Write engine/platform/src/console_font.h: the printable ASCII characters of
the X11 "fixed" 10x20 font (font-misc-misc: "Public domain font. Share and
enjoy."), one row of each glyph a 16-bit word, its leftmost pixel the top bit.

The Vita's text screen (vita.cpp, vita_console.h) draws with it: messages before the
game's picture exists, the host tests' results.

    python engine/platform/tools/make_console_font.py /usr/share/fonts/X11/misc/10x20.pcf.gz

(Debian/Ubuntu: xfonts-base.)
"""

import gzip
import io
import os
import sys

from PIL import PcfFontFile

WIDTH, HEIGHT = 10, 20


def main() -> None:
    path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/X11/misc/10x20.pcf.gz"
    data = open(path, "rb").read()
    if path.endswith(".gz"):
        data = gzip.decompress(data)
    font = PcfFontFile.PcfFontFile(io.BytesIO(data))
    # A glyph's box is placed from the baseline (y0 negative above it): the
    # cell's top is the full-height 'M''s top.
    ascent = -font.glyph[ord("M")][1][1]
    rows = []
    for code in range(32, 127):
        glyph = font.glyph[code]
        bitmap = [0] * HEIGHT
        if glyph:
            _, (x0, y0, x1, y1), _, image = glyph
            # dst box: x0..x1 from the origin, y0..y1 from the baseline (down positive in PIL's terms)
            for y in range(image.size[1]):
                for x in range(image.size[0]):
                    if image.getpixel((x, y)):
                        px, py = x0 + x, ascent + y0 + y
                        if 0 <= px < WIDTH and 0 <= py < HEIGHT:
                            bitmap[py] |= 0x8000 >> px
        rows.append(bitmap)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "console_font.h")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by engine/platform/tools/make_console_font.py from the X11 \"fixed\"\n")
        f.write("// 10x20 font (font-misc-misc: \"Public domain font. Share and enjoy.\").\n")
        f.write("// Printable ASCII (32-126); a glyph's rows top down, the leftmost pixel the top bit.\n\n")
        f.write("#ifndef PS2PLAT_CONSOLE_FONT_H\n#define PS2PLAT_CONSOLE_FONT_H\n\n#include <cstdint>\n\n")
        f.write("namespace ps2plat {\n\n")
        f.write("constexpr int kConsoleGlyphWidth = %d, kConsoleGlyphHeight = %d;\n" % (WIDTH, HEIGHT))
        f.write("constexpr std::uint16_t kConsoleFont[95][%d] = {\n" % HEIGHT)
        for code, bitmap in zip(range(32, 127), rows):
            f.write("    {%s},  // %r\n" % (", ".join("0x%04X" % r for r in bitmap), chr(code)))
        f.write("};\n\n}  // namespace ps2plat\n\n#endif  /* PS2PLAT_CONSOLE_FONT_H */\n")
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
