"""The Vita's code-size probe: assembly for an executable with as much code
as asked (in MB), to find whether the Vita's loader takes an executable the
size a whole translated game makes, and whether the linker's long-branch
veneers work across it.

The code is functions F_0 .. F_{K-1}, each a run of Thumb-2 arithmetic on r0
(adds r0, #c; eors r0, r1 with r1 = i), and in the first half a call to the
function half the code away (bl F_{i+K/2}: tens of MB, past a Thumb BL's 16
MB reach). main calls every one in turn through a table and compares the
result with what this script computed.

    python make_probe.py <MB> <out.S> <out.h>
"""

import sys

FUNCTION_BYTES = 64 * 1024


def main() -> None:
    megabytes = int(sys.argv[1])
    out_s, out_h = sys.argv[2], sys.argv[3]
    count = max(2, megabytes * 1024 * 1024 // FUNCTION_BYTES)
    pairs = (FUNCTION_BYTES - 32) // 4         # adds + eors: 2 + 2 bytes
    half = count // 2

    def filler(i: int, x: int) -> int:
        c = i % 200 + 1
        for _ in range(pairs):
            x = ((x + c) & 0xFFFFFFFF) ^ i
        return x

    # What main will compute, F_i in turn.
    def f(i: int, x: int) -> int:
        x = filler(i, x)
        if i < half:
            x = f(i + half, x)
        return x

    x = 0
    for i in range(count):
        x = f(i, x)
    expected = x

    # The fillers as machine code, one file for each constant, included
    # whole (.incbin): tens of MB of .rept'ed instructions took the assembler
    # gigabytes. adds r0, #c is 0x3000 | c; eors r0, r1 is 0x4048.
    import os
    import struct
    blob_dir = os.path.dirname(os.path.abspath(out_s))
    for c in range(1, 201):
        with open(os.path.join(blob_dir, "filler_%d.bin" % c), "wb") as blob:
            blob.write(struct.pack("<HH", 0x3000 | c, 0x4048) * pairs)

    with open(out_s, "w", newline="\n") as s:
        s.write("    .syntax unified\n    .thumb\n    .text\n")
        for i in range(count):
            c = i % 200 + 1
            # A section each, as -ffunction-sections gives compiled code: the
            # linker puts its long-branch veneers between input sections, so a
            # call within one section past 16 MB cannot be carried.
            s.write('    .section .text.probe_f%d, "ax", %%progbits\n' % i)
            s.write("    .align 2\n    .global probe_f%d\n    .type probe_f%d, %%function\n    .thumb_func\nprobe_f%d:\n" % (i, i, i))
            s.write("    push {r4, lr}\n    movw r1, #%d\n    movt r1, #%d\n" % (i & 0xFFFF, i >> 16))
            s.write('    .incbin "%s"\n' % os.path.join(blob_dir, "filler_%d.bin" % c).replace("\\", "/"))
            if i < half:
                s.write("    bl probe_f%d\n" % (i + half))
            s.write("    pop {r4, pc}\n    .size probe_f%d, .-probe_f%d\n" % (i, i))
        s.write("    .section .rodata\n    .align 2\n    .global probe_table\nprobe_table:\n")
        for i in range(count):
            s.write("    .word probe_f%d\n" % i)
    with open(out_h, "w", newline="\n") as h:
        h.write("// Generated by make_probe.py\n#include <cstdint>\n")
        h.write("constexpr unsigned kProbeMegabytes = %d, kProbeFunctions = %d;\n" % (megabytes, count))
        h.write("constexpr std::uint32_t kProbeExpected = 0x%08Xu;\n" % expected)
        h.write('extern "C" std::uint32_t (*const probe_table[%d])(std::uint32_t);\n' % count)
    print("probe: %d MB, %d functions, expected %08X" % (megabytes, count, expected))


if __name__ == "__main__":
    main()
